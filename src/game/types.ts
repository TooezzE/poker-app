// Типы данных игры. Здесь только описание того, как выглядят данные, — без логики.

/** Как ограничиваются ребаи. Можно выбрать только один способ. */
export type RebuyLimitKind =
  | 'none' // без ограничений
  | 'perPlayer' // не больше N ребаев на игрока
  | 'time' // только первые N минут игры
  | 'bigBlind' // только пока большой блайнд меньше N

/** Настройки, которые задаются до начала игры. */
export type Settings = {
  /** Стоимость входа в игру. */
  buyIn: number
  /** Стоимость одного ребая (докупки). */
  rebuyCost: number
  /** Сколько фишек получает игрок на старте и за каждый ребай. */
  startingStack: number
  /** Стартовый малый блайнд. */
  smallBlind: number
  /** Стартовый большой блайнд. */
  bigBlind: number
  /** Длительность одного уровня блайндов, в минутах. */
  levelMinutes: number
  /** Номинал самой мелкой фишки: все блайнды делятся на него, чтобы их можно было собрать. */
  minChip: number

  /** Способ ограничения ребаев. */
  rebuyLimit: RebuyLimitKind
  /** Для 'perPlayer': сколько ребаев можно одному игроку. */
  rebuyMaxPerPlayer: number
  /** Для 'time': сколько минут игрового времени (без пауз) открыты ребаи. */
  rebuyMinutes: number
  /** Для 'bigBlind': ребай можно, пока большой блайнд меньше этого числа. */
  rebuyBigBlindBelow: number
}

/** Игрок за столом. */
export type Player = {
  id: string
  name: string
  /** Сколько раз игрок сделал ребай. */
  rebuys: number
  /** Когда игрок выбыл (время в миллисекундах). null — сейчас в игре. */
  bustedAt: number | null
}

/**
 * Состояние таймера блайндов.
 *
 * Таймер не «тикает» сам — мы храним только отметки времени,
 * а текущий уровень и остаток времени вычисляем из них в любой момент.
 * Поэтому время считается верно, даже если телефон заблокирован или приложение свёрнуто.
 */
export type Clock = {
  /** Когда таймер поставили на паузу (мс). null — таймер идёт. */
  pausedAt: number | null
  /** Сколько всего длились прошлые паузы (мс). */
  pausedTotal: number
  /** Уровень, от которого идёт отсчёт (0 — первый уровень). */
  levelIndex: number
  /** Игровое время (мс с начала игры, без пауз), когда начался этот уровень. */
  levelStartedAt: number
}

/** Блайнды одного уровня. */
export type BlindLevel = {
  small: number
  big: number
}

/** Событие в истории игры: кто, что сделал, когда и при каких блайндах. */
export type GameEvent = {
  type: 'bust' | 'rebuy' | 'join' // вылет | ребай | опоздавший вошёл в игру
  playerId: string
  /** Когда произошло (мс). */
  at: number
  /** Номер уровня блайндов в этот момент (0 — первый). */
  level: number
  blinds: BlindLevel
}

/** Текущая игра целиком. */
export type Game = {
  settings: Settings
  players: Player[]
  /** Когда игра началась (время в миллисекундах). */
  startedAt: number
  /** Когда игру завершили и объявили победителя. null — игра идёт. */
  finishedAt: number | null
  clock: Clock
  /** История вылетов, ребаев и входов — по порядку. */
  events: GameEvent[]
}

/** Строка таблицы мест: игрок и его место (null — место ещё не определено). */
export type Standing = {
  player: Player
  place: number | null
}
